export async function fetchLiveRoadRoute(
  start: [number, number],
  end: [number, number] = SITE_COORDS
): Promise<[number, number][] | null> {
  try {
    const url = "https://router.project-osrm.org/route/v1/driving/" + start[1] + "," + start[0] + ";" + end[1] + "," + end[0] + "?overview=full&geometries=geojson";
    const res = await fetch(url, { signal: AbortSignal.timeout(4000) });
    const data = await res.json();
    if (data.routes && data.routes[0]?.geometry?.coordinates) {
      return data.routes[0].geometry.coordinates.map((c: [number, number]) => [
        Number(c[1].toFixed(6)),
        Number(c[0].toFixed(6)),
      ]);
    }
  } catch (err) {
    console.warn("OSRM dynamic route fallback to cached road points:", err);
  }
  return null;
}
